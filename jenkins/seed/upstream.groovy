def branchList = ['main', 'develop']

def playbookChoices = []
try {
    playbookChoices = readFileFromWorkspace('playbook-manifest.txt')
        .readLines()
        *.trim()
        .findAll { it && it != 'NO_PLAYBOOKS_FOUND' }
} catch (Exception e) {
    println "Ostrzeżenie: Nie udało się odczytać playbook-manifest.txt: ${e.message}"
}

if (!playbookChoices) {
    playbookChoices = ['brak_playbookow.yml']
}

def kubectlChoices = [
    'get pods -A',
    'get services -A',
    'describe pod <pod-name>'
]

def inventoryText = ''
try {
    inventoryText = readFileFromWorkspace('inventory-manifest.txt')
} catch (Exception e) {
    println "Warning: Failed to read inventory-manifest.txt: ${e.message}"
}

def ipMatcher = (inventoryText =~ /ansible_host:\s*["']?([0-9a-zA-Z\.\-]+)["']?/)
def serverIP = ipMatcher ? ipMatcher[0][1] : '127.0.0.1'

println "--> Detected SERVER_IP for pipelines: ${serverIP}"

def playbookChoicesLiteral = "[" + playbookChoices.collect { "'${it}'" }.join(', ') + "]"
def kubectlChoicesLiteral = "[" + kubectlChoices.collect { "'${it}'" }.join(', ') + "]"

branchList.each { branch ->

    pipelineJob("home_infra-${branch}") {
        description("Generated pipeline for branch: ${branch} (auto-generated by upstream.groovy)")

        environmentVariables {
            env('SERVER_IP', serverIP)
        }

        parameters {
            choiceParam('ACTION', ['Run Ansible Playbook', 'Execute Kubectl Command'], 'What do you want to run?')

            activeChoiceReactiveParam('PLAYBOOK') {
                description('Playbook to run — only relevant if ACTION = Run Ansible Playbook')
                choiceType('SINGLE_SELECT')
                filterable()
                groovyScript {
                    script("""
                        if (ACTION == 'Run Ansible Playbook') {
                            return ${playbookChoicesLiteral}
                        } else {
                            return ['N/A']
                        }
                    """)
                    fallbackScript('return ["ERROR"]')
                }
                referencedParameter('ACTION')
            }

            activeChoiceReactiveParam('KUBECTL_COMMAND') {
                description('kubectl command — only relevant if ACTION = Execute Kubectl Command')
                choiceType('SINGLE_SELECT')
                groovyScript {
                    script("""
                        if (ACTION == 'Execute Kubectl Command') {
                            return ${kubectlChoicesLiteral}
                        } else {
                            return ['N/A']
                        }
                    """)
                    fallbackScript('return ["ACTION"]')
                }

                stringParam('POD_NAME', '', 'Pod name — only needed for "describe pod <pod-name>"')
            }

            definition {
                cpsScm {
                    scm {
                        git {
                            remote {
                                url('https://github.com/Kobeep/home_infra.git')
                                credentials('github')
                            }
                            branches("*/${branch}")
                        }
                    }
                    scriptPath('jenkins/Jenkinsfile')
                    lightweight(true)
                }
            }

            logRotator {
                numToKeep(10)
                daysToKeep(7)
            }
        }
    }
}
